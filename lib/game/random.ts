// Deterministic pseudo-random shared by the scene's decorative layouts so
// the battlefield looks the same on every visit without shipping a scene
// file. Not for gameplay: matching rules live in ./matching.
export function seededRandom(seed: number): () => number {
  let state = seed | 0;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
